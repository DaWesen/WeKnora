// manifestTemplate renders a minimal but valid plugin.yaml for the given
// extension type. Capabilities are seeded to the empty set; authors add them
// as they implement features (e.g. document_parser gains "stream" when
// ParseStream is wired up).
//
// Network is enabled because the host rejects network-disabled process
// plugins (isolation is only enforceable under a container runtime). Plugins
// that must be offline ship a plugin.container.yaml instead — see the
// document-parser-plugin example.
func manifestTemplate(a scaffoldArgs) string {
	return fmt.Sprintf(`apiVersion: weknora.plugin/v1
kind: Plugin
metadata:
  id: %s
  name: %s
  version: 0.1.0
  description: TODO — replace with a short description of what this %s plugin does.
spec:
  extensionType: %s
  weknoraVersion: ">=0.1.0"
  capabilities: []
  entrypoint:
    type: process
    command: ["./%s"]
    grpcAddress: "%s"
  permissions:
    network:
      enabled: true
    filesystem: {}
  healthCheck:
    intervalSeconds: 30
    timeoutSeconds: 10
  restartPolicy:
    enabled: true
    maxAttempts: 3
    windowSeconds: 300
    backoffMillis: 5000
  configSchema:
    type: object
    properties: {}
`, a.ID, humanise(a.BinName), a.Type, a.Type, a.BinName, a.GRPCAddr)
}

// mainTemplate renders a runnable main.go implementing the extension service
// with Describe populated from the manifest and business RPCs returning
// Unimplemented so the plugin boots and passes the lifecycle half of the
// contract test before the author writes any real logic.
func mainTemplate(a scaffoldArgs) string {
	data := map[string]string{
		"ID":           a.ID,
		"Extension":    a.Type,
		"Registrar":    registrarCall(a.Type),
		"ServerStruct": serverStructTemplate(a.Type, humanise(a.BinName)),
	}
	tpl := template.Must(template.New("main").Parse(mainGoTemplate))
	var sb strings.Builder
	if err := tpl.Execute(&sb, data); err != nil {
		panic(err)
	}
	return sb.String()
}

