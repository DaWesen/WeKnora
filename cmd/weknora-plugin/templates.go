// registrarCall returns the literal SDK registrar invocation for the type.
func registrarCall(extType string) string {
	switch extType {
	case "datasource":
		return "pluginsdk.DataSourceService(s)"
	case "document_parser":
		return "pluginsdk.DocumentParserService(s)"
	case "web_search":
		return "pluginsdk.WebSearchService(s)"
	case "model_provider":
		return "pluginsdk.ModelProviderService(s)"
	case "retriever":
		return "pluginsdk.RetrieverService(s)"
	default:
		return "nil"
	}
}

func goModTemplate(a scaffoldArgs) string {
	base := fmt.Sprintf(`module %s

go 1.26.0

require github.com/Tencent/WeKnora/sdk/plugin v0.0.0-00010101000000-000000000000
`, a.Module)
	if a.SDKPath == "" {
		// No local checkout: rely on the published module once tagged.
		return base
	}
	// Local development: replace points at the caller's WeKnora checkout.
	// Quoted so paths with spaces parse correctly.
	return base + fmt.Sprintf(`
// Local development: points at a WeKnora checkout. Delete this replace and
// `+"`go get`"+` the published version before publishing the plugin.
replace github.com/Tencent/WeKnora/sdk/plugin => %q
`, filepath.ToSlash(a.SDKPath))
}

